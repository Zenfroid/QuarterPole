<section class="card card-body mb-3 page-text">
  <h1>How to play</h1>

  <h2>1. Open your stable</h2>
  <p>Log in on the forum, then come back to the game and name your stable.</p>

  <h2>2. Create your first horses</h2>
  <p>On your Dashboard, choose <strong>Create a foundation horse</strong>. Pick a name, sex, surface and age. Each one uses a creation credit. Older horses can race straight away; 2-year-olds have time to grow.</p>

  <h2>3. Read the trainer's notes</h2>
  <p>Open a horse to see its trainer's notes. They tell you what the horse is good at, and which distances and running style suit it. Hire a better trainer for a more reliable report.</p>

  <h2>4. Train</h2>
  <p>Press <strong>Train</strong> once a day on each horse that hasn't reached its peak. Training brings young horses on faster.</p>

  <h2>5. Enter a race</h2>
  <p>Go to <a href="races.php">Races</a>, pick a day and a race, and use <strong>Enter a horse</strong> at the bottom of the race page. Only horses that fit the race are listed. Watch your horse's Energy: rest it between races.</p>

  <h2>6. Check the results</h2>
  <p>After race time, open the race to see the chart: where each horse was at every call, the margins and the times. Purses go straight into your Cash.</p>

  <h2>7. Breed</h2>
  <p>When a horse's racing days are done, <strong>Retire to breeding</strong> on its page. Book your mares to stallions on the <a href="stallions.php">Stallions</a> page.</p>
  <p>Questions? Ask on the <a href="/Forum">forum</a>.</p>
</section>
